# Emits icall_imports.cpp: binds the libil2cpp icall implementations that the
# game code calls directly (named by icall_targets.py) to the same functions
# of the native libil2cpp.
#
# usage: python3 -I gen_icall_imports.py <libil2cpp.icalls> <icall_targets.json> <out.cpp>
import sys, json

icalls_path, targets_path, out_path = sys.argv[1:4]

# Overloads the caller signatures cannot tell apart, decided by the trampoline
# that binds each address (see docs/RECOMP_DESIGN.md).
OVERRIDES = {
    0x10d8b0: "System.Net.Sockets.Socket::Receive_internal(System.IntPtr,System.Net.Sockets.Socket/WSABUF*,System.Int32,System.Net.Sockets.SocketFlags,System.Int32&,System.Boolean)",
    0x10d978: "System.Net.Sockets.Socket::Receive_internal(System.IntPtr,System.Byte*,System.Int32,System.Net.Sockets.SocketFlags,System.Int32&,System.Boolean)",
    0x10da38: "System.Net.Sockets.Socket::Send_internal(System.IntPtr,System.Net.Sockets.Socket/WSABUF*,System.Int32,System.Net.Sockets.SocketFlags,System.Int32&,System.Boolean)",
    0x10db00: "System.Net.Sockets.Socket::Send_internal(System.IntPtr,System.Byte*,System.Int32,System.Net.Sockets.SocketFlags,System.Int32&,System.Boolean)",
    0x10ec3c: "System.Globalization.CompareInfo::internal_index(System.String,System.Int32,System.Int32,System.String,System.Globalization.CompareOptions,System.Boolean)",
    0x11262c: "System.Reflection.MethodBase::GetMethodFromHandleInternalType_native(System.IntPtr,System.IntPtr,System.Boolean)",
    0x113d2c: "System.Runtime.InteropServices.Marshal::PtrToStructure(System.IntPtr,System.Type)",
    0x1153b8: "System.Threading.NativeEventCalls::CreateEvent_internal(System.Boolean,System.Boolean,System.String,System.Int32&)",
    0x115958: "System.Threading.Thread::VolatileRead(System.Int32&)",
    0x115964: "System.Threading.Thread::VolatileWrite(System.Int32&,System.Int32)",
    0x11ef2c: "System.String::.ctor(System.Char[])",
}
# Translated from the arm64 image instead (self-contained leaf code).
TRANSLATED = range(0x187c98, 0x187e1c)
# Runtime internals the icall heuristic misnames: bound in runtime_imports.cpp.
# 0x130030 is ClassInlines::GetInterfaceInvokeDataFromVTableSlowPath (generic
# interface dispatch), not RuntimeType::GetNestedTypes_internal.
NOT_ICALLS = {0x130030}

headers, by_managed = {}, {}
header = None
for line in open(icalls_path):
    line = line.strip()
    if line.startswith(">"):
        header = line[1:]
        continue
    if not line or line.startswith("/"):
        continue
    managed, cpp = line.rsplit(" ", 1)
    by_managed[managed] = (cpp, header)

targets = json.load(open(targets_path))
bindings, skipped = [], []
for addr_text, info in sorted(targets.items(), key=lambda kv: int(kv[0], 16)):
    addr = int(addr_text, 16)
    if addr in TRANSLATED or addr in NOT_ICALLS:
        continue
    cands = info["candidates"]
    if addr in OVERRIDES:
        managed = OVERRIDES[addr]
    elif len({c["cpp"] for c in cands}) == 1:
        managed = cands[0]["managed"]
    else:
        if cands:
            skipped.append((addr, [c["managed"] for c in cands]))
        continue
    cpp, hdr = by_managed[managed]
    bindings.append((addr, cpp, hdr, managed))

with open(out_path, "w") as out:
    out.write("// Generated by tools/recomp/gen_icall_imports.py: libil2cpp icalls the game\n"
              "// code calls directly, keyed by their addresses in the macOS v1.4.2 arm64\n"
              "// GameAssembly and bound to the same functions of the native libil2cpp.\n")
    out.write('#include "il2cpp-config.h"\n')
    for hdr in sorted({b[2] for b in bindings}):
        out.write(f'#include "{hdr}"\n')
    out.write('\n#include "native_adapter.h"\n\nnamespace recomp\n{\n    void RegisterIcallImports()\n    {\n'
              "        using native::N;\n")
    for addr, cpp, hdr, managed in bindings:
        fn = cpp if cpp.startswith("ves_icall") or "::" not in cpp else f"il2cpp::icalls::{cpp}"
        out.write(f"        RegisterImport({addr:#x}, N<&{fn}>);  // {managed}\n")
    out.write("    }\n}\n")
print(f"{len(bindings)} icalls bound")
for addr, c in skipped:
    print(f"  unresolved {addr:#x}: {c}")
