# Builds the server endpoint catalog (request/response schemas) from an
# Il2CppDumper dump.cs. This is the specification for the offline server.
#
# usage: python3 -I gen_endpoint_catalog.py <dump.cs> <stringliteral.json> <script.json> <UnityFramework> <out.json> <out.md>
import sys, re, json, array
import lief

dump, literals, script, binary, out_json, out_md = sys.argv[1:7]
text = open(dump, encoding="utf-8", errors="replace").read()

# Split into type blocks: header line + body up to the closing brace at column 0.
types = {}
for m in re.finditer(r"^(?:public|internal|private|protected)[^\n]*?(?:class|struct|enum) ([^\s:<]+)[^\n]*// TypeDefIndex: \d+\n\{\n(.*?)^\}", text, re.S | re.M):
    types[m.group(1)] = m.group(2)

def fields(name):
    body = types.get(name)
    if body is None:
        return None
    sect = body.split("// Properties")[0].split("// Methods")[0]
    out = []
    for f in re.finditer(r"^\t(?:public|private|protected|internal) (?!const|static)([^;=]+?) ([A-Za-z_<>][\w<>]*); // 0x", sect, re.M):
        out.append({"type": f.group(1).replace("readonly ", ""), "name": f.group(2)})
    return out

def snake(s):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", s).lower()

php = sorted(set(re.findall(r'"value": "([a-z0-9_]+)\.php"', open(literals).read())))
php_set = set(php)

# Each request class returns its endpoint from GetPhpName() as a string literal.
# Read the literal slot it loads (adrp+add) and look it up in the literal table.
literal_at = {int(x["address"], 16): x["value"] for x in json.load(open(literals))}
php_name_rva = {m["Name"].split("$$")[0]: m["Address"] for m in json.load(open(script))["ScriptMethod"] if m["Name"].endswith("$$GetPhpName")}
macho = lief.parse(binary)
gen = macho.get_section("il2cpp")
gen_words = array.array("I", bytes(gen.content))

def php_name_of(cls):
    rva = php_name_rva.get(cls)
    if rva is None:
        return None
    idx = (rva - gen.virtual_address) // 4
    pages = [None] * 32
    for i in range(idx, idx + 24):
        ins = gen_words[i]
        if ins & 0x9F000000 == 0x90000000:
            imm = (((ins >> 5) & 0x7FFFF) << 2) | ((ins >> 29) & 3)
            if imm & (1 << 20):
                imm -= 1 << 21
            pages[ins & 31] = ((gen.virtual_address + i * 4) & ~0xFFF) + (imm << 12)
        elif ins & 0xFF800000 == 0x91000000 and pages[(ins >> 5) & 31] is not None:
            value = literal_at.get(pages[(ins >> 5) & 31] + ((ins >> 10) & 0xFFF))
            if value and value.endswith(".php"):
                return value[:-4]
        elif ins == 0xD65F03C0:  # ret
            break
    return None

def resolve_types(fs, depth=0, seen=None):
    # Expand nested protocol types (e.g. FooResultProtocol.BODY) one level at a time.
    seen = seen or set()
    nested = {}
    for f in fs or []:
        for t in re.findall(r"[\w.]+", f["type"]):
            if t in types and t not in seen and ("Protocol" in t or "." in t) and depth < 4:
                seen.add(t)
                sub = fields(t)
                if sub is not None:
                    nested[t] = sub
                    nested.update(resolve_types(sub, depth + 1, seen))
    return nested

catalog = []
matched = set()
for cls in sorted(n for n in types if re.fullmatch(r"bsNetReq[A-Z][A-Za-z0-9]*", n) and n != "bsNetReqBase"):
    if not re.search(r":\s*bsNetReqBase\b", text[text.find("class " + cls + " "):][:200]):
        continue
    endpoint = php_name_of(cls)
    if endpoint is None:
        name = snake(cls[len("bsNetReq"):])
        endpoint = name if name in php_set else None
    if endpoint:
        matched.add(endpoint)
    req = fields(cls + ".RequestData") or []
    m = re.search(r"Action<(\w+Protocol)> m_callback", types[cls]) or re.search(r"Action<(\w+Protocol)>", types[cls])
    res_type = m.group(1) if m else None
    res = fields(res_type) if res_type else None
    entry = {
        "class": cls,
        "endpoint": (endpoint + ".php") if endpoint else None,
        "request": req,
        "response_type": res_type,
        "response": res,
        "types": resolve_types((req or []) + (res or [])),
    }
    catalog.append(entry)

unmatched = sorted(p + ".php" for p in php_set - matched)
json.dump({"endpoints": catalog, "unmatched_php": unmatched}, open(out_json, "w"), indent=1)

def fmt(fs):
    return ", ".join(f"`{f['name']}: {f['type']}`" for f in fs) if fs else "(none)"

with open(out_md, "w") as md:
    md.write("# Server endpoint catalog\n\nGenerated by `tools/server/gen_endpoint_catalog.py`. ")
    md.write(f"{len(catalog)} request classes, {len(php)} PHP endpoint names.\n\n")
    for e in catalog:
        md.write(f"## {e['endpoint'] or '(no endpoint match)'}\n\n`{e['class']}` -> `{e['response_type']}`\n\n")
        md.write(f"- Request: {fmt(e['request'])}\n- Response: {fmt(e['response'])}\n")
        for t, fs in e["types"].items():
            md.write(f"  - `{t}`: {fmt(fs)}\n")
        md.write("\n")
    md.write("## Endpoint names without a request class\n\n" + "\n".join(f"- {u}" for u in unmatched) + "\n")

print("request classes:", len(catalog), "matched endpoints:", len(matched), "unmatched php:", len(unmatched))
print("no response type:", [e["class"] for e in catalog if not e["response_type"]][:20])
