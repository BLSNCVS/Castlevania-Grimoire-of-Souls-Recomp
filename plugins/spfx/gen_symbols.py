# Generates spfx_symbols.cpp: image addresses of the plugin's own symbols
# that dyld binds back into the image (weak vtables, static guards), so the
# host can bind them without a symbol table parser.
#
# usage: python3 -I gen_symbols.py <arm64 Mach-O> <out.cpp>
import sys

import lief

binary, out = sys.argv[1:3]
b = lief.parse(binary)
defined = {s.name: s.value for s in b.symbols if s.value and s.name}
bound = {bi.symbol.name for bi in b.bindings if bi.has_symbol}
# plus the entry points the host calls by name
entry = {"_UnityPluginLoad", "_UnityPluginUnload", "_SPFX_PLUGIN_GetRenderingCallback"}
rows = sorted((n, defined[n]) for n in bound | entry if n in defined)
with open(out, "w") as f:
    f.write("// Generated by plugins/spfx/gen_symbols.py\n#include <cstddef>\n#include <cstdint>\n\n")
    f.write("namespace spfx\n{\n    struct DefinedSymbol { const char* name; uint64_t address; };\n")
    f.write("    extern const DefinedSymbol kDefinedSymbols[] = {\n")
    for n, a in rows:
        f.write(f'        {{ "{n}", {a:#x} }},\n')
    f.write("    };\n")
    f.write(f"    extern const size_t kDefinedSymbolCount = {len(rows)};\n")
    # C++ static initializers, run in order once the image is bound
    init = b.get_section("__mod_init_func")
    f.write(f"    extern const uint64_t kModInitFunc = {init.virtual_address if init else 0:#x};\n")
    f.write(f"    extern const size_t kModInitCount = {init.size // 8 if init else 0};\n}}\n")
print(f"{len(rows)} self-bound symbols")
